// ── Helpers ───────────────────────────────────────

export function getEspersByElement(element) {
  return ESPERS.filter(e => e.element === element)
}

export function getEspersByRole(role) {
  return ESPERS.filter(e => e.role === role)
}

export function getEspersByTier(tier) {
  return ESPERS.filter(e => e.tier === tier)
}

export function getEsperById(id) {
  return ESPERS.find(e => e.id === id) || null
}

export function getBestEspersForMode(mode) {
  return ESPERS
    .filter(e => e.modes[mode] === 'SS' || e.modes[mode] === 'S')
    .sort((a, b) => {
      const order = { SS: 0, S: 1 }
      return (order[a.modes[mode]] ?? 2) - (order[b.modes[mode]] ?? 2)
    })
}

export default ESPERS
